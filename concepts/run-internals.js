// Runs every "Behind the scenes" Python program with python3 and saves what it prints into
// how-internals-output.js, so each page can show the real output. It doubles as a test:
// it stops with an error if any program fails. Usage (from anywhere):
//   node concepts/run-internals.js            run all
//   node concepts/run-internals.js kvcache    run one (id without "hw-") and print its output
// Then regenerate the pages: node concepts/gen-how-pages.js
const fs = require("fs");
const os = require("os");
const path = require("path");
const vm = require("vm");
const { spawnSync } = require("child_process");

const FILES = ["how-internals-1.js", "how-internals-2.js", "how-internals-3.js"];
const ctx = { window: {} };
vm.createContext(ctx);
for (const f of FILES) {
  const p = path.join(__dirname, f);
  if (fs.existsSync(p)) vm.runInContext(fs.readFileSync(p, "utf8"), ctx, { filename: f });
}
const ALL = ctx.window.HOW_INTERNALS || {};
const only = process.argv[2] ? "hw-" + process.argv[2].replace(/^hw-/, "") : null;
const ids = Object.keys(ALL).filter((id) => !only || id === only);
if (!ids.length) { console.error(only ? `No program for ${only}` : "No programs found"); process.exit(1); }

const OUT_FILE = path.join(__dirname, "how-internals-output.js");
const outputs = {};
if (fs.existsSync(OUT_FILE)) {
  const c = { window: {} };
  vm.createContext(c);
  vm.runInContext(fs.readFileSync(OUT_FILE, "utf8"), c);
  Object.assign(outputs, c.window.HOW_INTERNALS_OUTPUT || {});
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "how-internals-"));
let failed = 0;
for (const id of ids) {
  const file = path.join(tmp, id.replace(/-/g, "_") + ".py");
  fs.writeFileSync(file, ALL[id].code);
  // -I: isolated mode (ignores user site-packages and env vars), so only the standard library is used
  const r = spawnSync("python3", ["-I", file], { cwd: tmp, encoding: "utf8", timeout: 20000, env: { ...process.env, PYTHONIOENCODING: "utf-8" } });
  if (r.status !== 0) {
    failed++;
    console.error(`FAIL ${id}\n${(r.stderr || r.error || "").toString().trim()}\n`);
    continue;
  }
  const out = r.stdout.replace(/\s+$/, "");
  const lines = out.split("\n");
  if (lines.length > 40) console.warn(`warn ${id}: long output (${lines.length} lines)`);
  outputs[id] = out;
  if (only) console.log(out);
}
fs.rmSync(tmp, { recursive: true, force: true });

if (failed) { console.error(`${failed} program(s) failed; output file not updated.`); process.exit(1); }
const sorted = Object.fromEntries(Object.keys(outputs).sort().map((k) => [k, outputs[k]]));
fs.writeFileSync(OUT_FILE, `// Generated by concepts/run-internals.js - the real output of each "Behind the scenes" program.
(function (root) {
  root.HOW_INTERNALS_OUTPUT = ${JSON.stringify(sorted, null, 2)};
})(typeof window !== "undefined" ? window : globalThis);
`);
console.log(`Ran ${ids.length} program(s) OK; ${Object.keys(sorted).length} outputs saved to concepts/how-internals-output.js`);
