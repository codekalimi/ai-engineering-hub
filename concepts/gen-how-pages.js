// Writes one page per "How it works" explanation into concepts/how/, and refreshes the
// topic list in the left index (assets/site.js). Run from anywhere, no install needed:
//   node concepts/gen-how-pages.js
// Content lives in how-it-works-data.js / how-it-works-data-2.js; page names, short titles
// and related links live in how-meta.js.
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const SITE = path.resolve(__dirname, "..");
const OUT = path.join(__dirname, "how");
const R = require(path.join(SITE, "assets/howitworks.js"));
const esc = R.esc;

// Load the browser data files the same way the cheat sheet does
const ctx = { window: {} };
vm.createContext(ctx);
const DATA_FILES = ["how-it-works-data.js", "how-it-works-data-2.js", "how-meta.js",
  "how-internals-1.js", "how-internals-2.js", "how-internals-3.js", "how-internals-output.js"];
for (const f of DATA_FILES) {
  vm.runInContext(fs.readFileSync(path.join(__dirname, f), "utf8"), ctx, { filename: f });
}
const { HOW, HOW_META: META } = ctx.window;
const BTS = ctx.window.HOW_INTERNALS || {}, BTS_OUT = ctx.window.HOW_INTERNALS_OUTPUT || {};

// ---- Check the data before writing anything ----
const errors = [];
const byId = new Map(HOW.items.map((it) => [it.id, it]));
const catOf = new Map(HOW.cats.map((c) => [c.id, c]));
const slugs = new Set();
for (const it of HOW.items) {
  const m = META[it.id];
  if (!catOf.has(it.cat)) errors.push(`${it.id}: unknown category ${it.cat}`);
  if (!m) { errors.push(`${it.id}: missing from how-meta.js`); continue; }
  if (!/^[a-z0-9-]+$/.test(m.slug)) errors.push(`${it.id}: bad file name "${m.slug}"`);
  if (slugs.has(m.slug)) errors.push(`${it.id}: duplicate file name "${m.slug}"`);
  slugs.add(m.slug);
  for (const r of m.related) {
    if (!byId.has(r)) errors.push(`${it.id}: related "${r}" does not exist`);
    if (r === it.id) errors.push(`${it.id}: related to itself`);
  }
}
for (const id of Object.keys(META)) if (!byId.has(id)) errors.push(`how-meta.js: "${id}" has no explanation`);
for (const id of Object.keys(BTS)) if (!byId.has(id)) errors.push(`how-internals: "${id}" has no explanation`);
const noBts = HOW.items.filter((it) => !BTS[it.id]).map((it) => it.id);
const noOut = HOW.items.filter((it) => BTS[it.id] && !BTS_OUT[it.id]).map((it) => it.id);
if (noBts.length) console.warn(`No "Behind the scenes" program yet for: ${noBts.join(", ")}`);
if (noOut.length) console.warn(`Output missing (run node concepts/run-internals.js) for: ${noOut.join(", ")}`);
if (errors.length) { console.error("Not generated:\n  " + errors.join("\n  ")); process.exit(1); }

// Reading order: by category, then the order in the data files
const ordered = HOW.cats.flatMap((c) => HOW.items.filter((it) => it.cat === c.id));
const pageId = (it) => "concepts/how/" + META[it.id].slug;
const file = (it) => META[it.id].slug + ".html";

function page(it, i) {
  const m = META[it.id], cat = catOf.get(it.cat);
  const inCat = ordered.filter((x) => x.cat === it.cat);
  const pos = inCat.indexOf(it) + 1;
  const prev = ordered[i - 1], next = ordered[i + 1];
  const kinds = R.diagrams(it).map((d) => d.type);
  const howToRead = kinds.includes("seq")
    ? "Sequence diagram: read top to bottom. Each numbered arrow is one message between two parts of the system; dashed boxes are notes."
    : "Flow diagram: read left to right. Dashed loops show steps that repeat; ↓ joins rows that follow on from each other.";
  const pn = (x, dir) => x ? `<a class="tn ${dir}" href="${file(x)}">
          <span class="label">${dir === "prev" ? "← Previous" : "Next →"}${x.cat !== it.cat ? ` · ${esc(catOf.get(x.cat).title)}` : ""}</span>
          <b>${esc(META[x.id].short)}</b>
        </a>` : `<span class="tn ${dir} none"></span>`;
  const related = m.related.map((rid) => {
    const r = byId.get(rid);
    return `<a class="card" href="${file(r)}">
            <span class="label">${esc(catOf.get(r.cat).title)}</span>
            <h3>${esc(META[rid].short)}</h3>
            <p>${esc(r.q)}</p>
          </a>`;
  }).join("");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="claude:viewport-fit-sides" content="cover">
<title>${esc(m.short)} · How It Works</title>
<meta name="description" content="${esc(it.tldr)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;500&family=Space+Grotesk:wght@500;600;700&display=swap">
<link rel="stylesheet" href="../../assets/site.css">
</head>
<body>
<!-- Generated by concepts/gen-how-pages.js. Edit the data files, not this page. -->
<div class="shell" data-root="../../" data-page="${pageId(it)}">
  <nav class="sidebar" id="sidebar" aria-label="Index"></nav>
  <div class="scrim"></div>
  <div class="main">
    <div class="topbar">
      <button class="icon-btn" id="navToggle" type="button" aria-controls="sidebar"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M4 6h16M4 12h16M4 18h16"/></svg><span class="t">Index</span></button>
      <span class="crumbs"><a href="../../index.html">Home</a> / <a href="../how-it-works.html">Concepts</a> / <a href="../how-it-works.html#${cat.id}">${esc(cat.title)}</a> / ${esc(m.short)}</span>
    </div>
    <main class="content topic">
      <header class="page-head">
        <span class="eyebrow">${esc(cat.title)} · ${pos} of ${inCat.length}</span>
        <h1>${esc(it.q)}</h1>
        <p class="tldr"><span class="label">In one line</span>${esc(it.tldr)}</p>
        ${BTS[it.id] ? `<p class="jump"><a href="#behind-the-scenes">↓ Behind the scenes: run it yourself in plain Python</a></p>` : ""}
      </header>

      <article class="hw hw-page" id="${it.id}">
        <details class="howto">
          <summary>How to read this diagram</summary>
          <p>${howToRead}</p>
          ${R.legend()}
        </details>
        ${R.body(it)}
      </article>

      ${R.behind(BTS[it.id], BTS_OUT[it.id], { guide: "../behind-the-scenes.html" })}

      <nav class="topic-nav" aria-label="Previous and next explanation">
        ${pn(prev, "prev")}
        ${pn(next, "next")}
      </nav>

      <section class="section" id="related">
        <div class="section-head"><h2>Related</h2></div>
        <div class="cards">
          ${related}
        </div>
      </section>

      <footer>See this with all ${ordered.length} explanations on the <a href="../how-it-works.html#${it.id}">one-page cheat sheet</a>. Numbers are typical values for explanation; check current docs for exact figures.</footer>
    </main>
  </div>
</div>
<script src="../../assets/site.js"></script>
</body>
</html>
`;
}

// ---- Write the pages (replacing any old generated ones) ----
fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) if (f.endsWith(".html")) fs.unlinkSync(path.join(OUT, f));
ordered.forEach((it, i) => fs.writeFileSync(path.join(OUT, file(it)), page(it, i)));

// ---- Refresh the left index: one entry per category, its topics underneath ----
const navFile = path.join(SITE, "assets/site.js");
const nav = fs.readFileSync(navFile, "utf8");
const BEGIN = "// BEGIN generated by concepts/gen-how-pages.js (do not edit by hand)";
const END = "// END generated";
const a = nav.indexOf(BEGIN), b = nav.indexOf(END);
if (a < 0 || b < a) { console.error("Markers not found in assets/site.js"); process.exit(1); }
const indent = "        ";
const entries = HOW.cats.map((c) => {
  const subs = ordered.filter((it) => it.cat === c.id)
    .map((it) => `[${JSON.stringify("concepts/how/" + file(it))}, ${JSON.stringify(META[it.id].short)}, ${JSON.stringify(pageId(it))}]`);
  return `${indent}{ id: ${JSON.stringify("concepts/how-section/" + c.id)}, title: ${JSON.stringify(c.title)}, href: ${JSON.stringify("concepts/how-it-works.html#" + c.id)},\n${indent}  subs: [\n${subs.map((s) => indent + "    " + s).join(",\n")},\n${indent}  ] },`;
}).join("\n");
fs.writeFileSync(navFile, nav.slice(0, a) + BEGIN + "\n" + entries + "\n" + indent + nav.slice(b));

console.log(`Wrote ${ordered.length} pages to concepts/how/ and ${HOW.cats.length} index sections to assets/site.js`);
